def translate(text, lang):
    return TRANSLATIONS.get(lang, {}).get(text, text)


def get_profile(user):
    if not user.is_authenticated:
        return None
    try:
        return user.evaluator_profile
    except Exception:  # RelatedObjectDoesNotExist: admins creados por consola no tienen perfil
        return None


_ASSETS = ('css/admin_panel.css', 'css/settings_panel.css', 'css/panel_auth.css', 'js/avatar_picker.js')


def asset_version():
    """Cambia cada vez que se edita un CSS/JS del panel, para que el navegador no use una copia vieja."""
    import os
    base = os.path.join(os.path.dirname(__file__), 'static')
    try:
        return str(int(max(os.path.getmtime(os.path.join(base, f)) for f in _ASSETS)))
    except OSError:
        return '1'


def panel_preferences(request):
    """Context processor: idioma y color del usuario para todas las plantillas."""
    profile = get_profile(getattr(request, 'user', None)) if hasattr(request, 'user') else None
    lang = profile.language if profile and profile.language in LANGUAGE_CODES else DEFAULT_LANGUAGE
    accent_key = profile.accent_color if profile and profile.accent_color in ACCENT_KEYS else DEFAULT_ACCENT
    _, _, light, dark = next(c for c in ACCENT_COLORS if c[0] == accent_key)
    palette = accent_palette(light, dark)
    shortcuts = resolve_shortcuts(profile)
    return {
        'asset_v': asset_version(),
        'panel_lang': lang,
        'panel_accent': {'key': accent_key, 'light': light, 'dark': dark, 'style': accent_style(palette)},
        'panel_shortcuts': shortcuts,
        'panel_shortcut_labels': {a: shortcut_label(k) for a, k in shortcuts.items()},
        'panel_shortcuts_enabled': profile.shortcuts_enabled if profile else True,
    }
