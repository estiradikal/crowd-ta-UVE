def is_valid_shortcut_key(key):
    return key in NAMED_KEYS or (len(key) == 1 and key.isprintable())


def shortcut_label(key):
    return NAMED_KEYS.get(key, key.upper())


def resolve_shortcuts(profile):
    keys = dict(DEFAULT_SHORTCUTS)
    if profile and isinstance(profile.shortcuts, dict):
        keys.update({a: k for a, k in profile.shortcuts.items() if a in keys and is_valid_shortcut_key(k)})
    return keys


