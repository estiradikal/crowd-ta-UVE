def _mix(color, other, weight):
    """Mezcla dos colores hex: weight=1 devuelve color, weight=0 devuelve other."""
    a = [int(color[i:i + 2], 16) for i in (1, 3, 5)]
    b = [int(other[i:i + 2], 16) for i in (1, 3, 5)]
    return '#' + ''.join('%02x' % round(x * weight + y * (1 - weight)) for x, y in zip(a, b))


def accent_palette(light, dark):
    """Variables CSS de un color de acento (se calculan aquí para no depender de color-mix del navegador)."""
    return {
        '--accent-light': light,
        '--accent-dark': dark,
        '--accent-soft-light': _mix(light, '#ffffff', 0.12),
        '--accent-soft-dark': _mix(dark, '#1e293b', 0.25),
        '--accent-bg-light': _mix(light, '#f5f6fa', 0.06),
        '--accent-bg-dark': _mix(dark, '#0f172a', 0.07),
        '--accent-tint-light': _mix(light, '#ffffff', 0.07),
        '--accent-tint-dark': _mix(dark, '#1e293b', 0.10),
        '--accent-deep': _mix(light, '#0f172a', 0.55),
        '--accent-rgb': ', '.join(str(int(light[i:i + 2], 16)) for i in (1, 3, 5)),
    }


